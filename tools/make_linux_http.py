#!/usr/bin/env python3
"""Generate Linux x86-64 HTTP bridge assembly from the shared native source."""
from pathlib import Path
import platform
import re
import shutil
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / 'rt/http/native.c'
OUTPUT = ROOT / 'rt/http/linux_native.s'


def main():
    if platform.system() == 'Darwin':
        zig = shutil.which('zig')
        if not zig:
            raise SystemExit('Linux HTTP generation requires zig cc on macOS')
        sdk = subprocess.check_output(['xcrun', '--show-sdk-path'], text=True).strip()
        compiler = [zig, 'cc', '-target', 'x86_64-linux-gnu', '-isystem', sdk + '/usr/include']
    else:
        compiler = ['cc']
    with tempfile.TemporaryDirectory(prefix='bit-linux-http-') as folder:
        output = Path(folder) / 'http.s'
        subprocess.run(compiler + ['-DBIT_HTTP_LINUX', '-S', '-O1', '-g0',
                                   '-fno-stack-protector', '-fno-asynchronous-unwind-tables',
                                   '-Wno-deprecated-declarations', '-masm=intel',
                                   str(SOURCE), '-o', str(output)], check=True)
        assembly = output.read_text()
    assembly = re.sub(r'^\s*\.(?:file|loc|cfi_\w+|ident|addrsig\w*|intel_syntax)\b[^\n]*\n', '', assembly, flags=re.M)
    assembly = re.sub(r'^\s*\.section\s+"?\.note\.GNU-stack"?[^\n]*\n', '', assembly, flags=re.M)
    assembly = re.sub(r'\.L([A-Za-z0-9_.$]+)', r'.Lbit_http_\1', assembly)
    for symbol in ('_bit_fetch:', '_bit_http_post:', '_bit_download:', '_bit_die'):
        if symbol not in assembly:
            raise RuntimeError(f'Linux HTTP assembly missing {symbol}')
    OUTPUT.write_text('# Generated by tools/make_linux_http.py; do not edit.\n' + assembly.rstrip() + '\n.text\n')
    print(f'{OUTPUT.relative_to(ROOT)}: Linux HTTP bridge generated')


if __name__ == '__main__':
    main()
